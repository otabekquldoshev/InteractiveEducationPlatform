type TranslationKey =
  | keyof typeof dictionary.uz
  | keyof typeof extraDictionary.uz
  | keyof typeof adminDictionary.uz
interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey) => string
}
const LanguageContext = createContext<LanguageContextValue | null>(null)
const STORAGE_KEY = "edu_language"

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_KEY)
    return saved && saved in dictionary ? (saved as Language) : "uz"
  })
  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])
  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (key: TranslationKey) =>
        (adminDictionary as any)[language]?.[key] ||
        (extraDictionary as any)[language]?.[key] ||
        (dictionary as any)[language]?.[key] ||
        (adminDictionary.uz as any)[key] ||
        (extraDictionary.uz as any)[key] ||
        (dictionary.uz as any)[key] ||
        key,
    }),
    [language],
  )
  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context)
    throw new Error("useLanguage must be used inside LanguageProvider")
  return context
}
